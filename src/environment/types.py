MAX_EFFECTIVENESS = 3.0   # 多系克制封顶（2×2 → 3，不乘到 4）
STAB_MULT = 1.25           # 同系加成

_TYPES_SET: frozenset[str] = frozenset(TYPE_NAMES)


def normalize_type(t: str) -> str:
    """未知系别回退「普通」（表外数据不抛、不炸）。"""
    return t if t in _TYPES_SET else "普通"


def type_effectiveness(atk_type: str, def_types) -> float:
    """攻击系别 vs 防守系别集合 → 倍率。

    多系别：逐个查 CHART[防御][攻击] 取乘积，**克制封顶 ×3，抵抗正常乘算**
    （统一 `min(∏, MAX_EFFECTIVENESS)` 实现）。未知系别一律中性 1.0。
    """
    atk = normalize_type(atk_type)
    eff = 1.0
    for dt in def_types or ():
        eff *= CHART[normalize_type(dt)][atk]
    return min(eff, MAX_EFFECTIVENESS)


def stab_multiplier(skill_type: str, attacker_types) -> float:
    """STAB：技能系别命中攻击方自身系别 → 1.25，否则 1.0。"""
    st = normalize_type(skill_type)
    return STAB_MULT if st in {normalize_type(t) for t in (attacker_types or ())} else 1.0
